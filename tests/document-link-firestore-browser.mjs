import '../scripts/test-guard.mjs';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { readFile } from 'node:fs/promises';
import { initializeTestEnvironment } from '@firebase/rules-unit-testing';
import { doc, setDoc, getDoc, updateDoc, Timestamp } from 'firebase/firestore';
import { workerFixture } from './worker-browser-fixture.mjs';
import { OWNER_UID } from '../js/permissions.js';
const require = createRequire(resolve(process.env.ACERVO_TEST_MODULES, 'package.json'));
const { chromium } = require('playwright'), { PDFDocument } = require('pdf-lib');
const project = 'demo-acervo', base = process.env.ACERVO_TEST_URL || 'http://127.0.0.1:4186';
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '') || !/^127\.0\.0\.1:\d+$/.test(process.env.FIREBASE_AUTH_EMULATOR_HOST || '')) throw new Error('Exige emuladores locais.');
const port = Number(process.env.FIRESTORE_EMULATOR_HOST.split(':')[1]);
const env = await initializeTestEnvironment({ projectId: project, firestore: { host: '127.0.0.1', port, rules: await readFile('firestore.rules', 'utf8') } });
const backend = await workerFixture({ project, origin: base, initialFiles: [] });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], blocked = [];
try {
  await fetch(`http://${process.env.FIREBASE_AUTH_EMULATOR_HOST}/identitytoolkit.googleapis.com/v1/projects/${project}/accounts`, { method: 'POST', headers: { Authorization: 'Bearer owner', 'Content-Type': 'application/json' }, body: JSON.stringify({ localId: OWNER_UID, email: 'link-owner@example.test', password: 'Fixture-password-123' }) });
  await env.withSecurityRulesDisabled(async (c) => {
    await setDoc(doc(c.firestore(), 'users', OWNER_UID), { uid: OWNER_UID, email: 'link-owner@example.test', name: 'Owner', role: 'superadmin', status: 'approved', permissions: { approveUsers: true, addGames: true, editGames: true, deleteGames: true }, createdAt: Timestamp.now(), updatedAt: Timestamp.now(), version: 1, lastEventId: '' });
    await setDoc(doc(c.firestore(), 'settings', 'library'), { publicRead: false, version: 1, updatedAt: Timestamp.now(), lastEventId: '' });
  });
  const context = await browser.newContext({ serviceWorkers: 'block' });
  await context.route('**/*', (route) => { const url = new URL(route.request().url()); if (!['127.0.0.1', 'localhost'].includes(url.hostname)) { blocked.push(url.origin); return route.abort(); } return route.continue(); });
  await context.route('**/config/app-config.js', (route) => route.fulfill({ contentType: 'text/javascript', body: `export const APP_CONFIG=${JSON.stringify({ firebase: { apiKey: 'demo-key', projectId: project, authDomain: 'demo-acervo.firebaseapp.com', appId: '1:000:web:links' }, ownerUid: OWNER_UID, sdkBase: '/__dev/sdk', emulators: { auth: `http://${process.env.FIREBASE_AUTH_EMULATOR_HOST}`, host: '127.0.0.1', port }, fileStorage: { apiBase: backend.apiBase }, maxPdfBytes: 52428800 })};` }));
  await context.route('**/v1/research/sources', (route) => route.fulfill({ json: { protocol: 2, sources: [] } }));
  await context.route('**/js/document-repository.js', async (route) => {
    const response = await route.fetch();
    const source = (await response.text()).replace('await sdk.runTransaction(db, async (tx) => {', 'if (window.__failDocumentLinks) throw new Error("Falha simulada ao gravar vínculo no Firestore."); await sdk.runTransaction(db, async (tx) => {');
    await route.fulfill({ response, body: source });
  });
  const page = await context.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('dialog', (dialog) => dialog.accept());
  await page.goto(base);
  await page.locator('#login-form [name=email]').fill('link-owner@example.test');
  await page.locator('#login-form [name=password]').fill('Fixture-password-123');
  await page.locator('#login-submit').click();
  await page.locator('[data-add]').first().click();
  const files = [];
  for (const name of ['Betrayal - Livro de regras', 'Tomo do traidor', 'Segredos de sobrevivencia', 'Referencia rapida']) {
    const pdf = await PDFDocument.create(); pdf.setTitle(name);
    pdf.addPage().drawText(`${name}: coloque as cartas na mesa e consulte o cenario para iniciar o turno.`, { x: 30, y: 700, size: 12 });
    files.push({ name: `${name}.pdf`, mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) });
  }
  if (process.env.ACERVO_TEST_PRIMARY_PDF) files[0] = { name: 'betrayal_at_house_on_livro_de_regras_210149.pdf', mimeType: 'application/pdf', buffer: await readFile(process.env.ACERVO_TEST_PRIMARY_PDF) };
  await page.locator('#pdf-file').setInputFiles(files[0]);
  await page.locator('#game-title').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('#registration-pdfs').disabled);
  await page.locator('#additional-pdf-file').setInputFiles(files.slice(1));
  await page.waitForFunction(() => document.querySelectorAll('[data-registration-document]').length === 3 && !document.querySelector('#registration-pdfs').disabled);
  await page.locator('#game-title').fill('Betrayal at House on the Hill');
  await page.locator('[data-step-target="3"]').click(); await page.locator('[name=confirmed]').check();
  await page.evaluate(() => { window.__failDocumentLinks = true; });
  await page.locator('#save-game').click();
  await page.waitForFunction(() => !document.querySelector('#save-error').hidden && document.querySelector('#save-error').textContent.includes('alguns PDFs'), null, { timeout: 60000 });
  const records = await (await fetch(`http://${process.env.FIRESTORE_EMULATOR_HOST}/v1/projects/${project}/databases/(default)/documents/games`, { headers: { Authorization: 'Bearer owner' } })).json();
  const id = records.documents[0].name.split('/').at(-1);
  let game;
  const inspect = () => env.withSecurityRulesDisabled(async (c) => { game = (await getDoc(doc(c.firestore(), 'games', id))).data(); });
  await inspect();
  assert.equal(Object.keys(game.documents || {}).length, 0, 'nenhum vínculo parcial é anunciado como concluído');
  assert.equal([...backend.files.values()].filter((file) => file.mimeType === 'application/pdf').length, 4, 'os quatro PDFs já chegaram ao Drive simulado');
  const uploadedPdfIds = () => [...backend.files.values()].filter((file) => file.mimeType === 'application/pdf').map((file) => file.id).sort();
  const uploadedBeforeReload = uploadedPdfIds();
  const sourceFields = process.env.ACERVO_TEST_GAME_METADATA ? (await import('../worker/src/services.js')).decodeFields(JSON.parse(await readFile(process.env.ACERVO_TEST_GAME_METADATA, 'utf8'))[0].fields).sources : { title: { source: 'Correção manual', excerpt: 'Betrayal' } };
  await env.withSecurityRulesDisabled((c) => updateDoc(doc(c.firestore(), 'games', id), { sources: sourceFields, description: 'Resumo corrigido em outra sessão durante o envio.', updatedAt: Timestamp.now() }));
  await page.reload();
  await page.locator('.card-main').click();
  await page.locator('#detail-documents .document-link-pending button').waitFor();
  await page.locator('#detail-documents .document-link-pending button').click();
  await page.waitForFunction(() => document.querySelectorAll('#detail-documents .document-reading-row').length === 4 && !document.querySelector('#detail-documents .document-link-pending'), null, { timeout: 45000 });
  await inspect();
  assert.equal(Object.keys(game.documents).length, 4);
  assert.equal(game.description, 'Resumo corrigido em outra sessão durante o envio.');
  assert.deepEqual(game.sources, sourceFields);
  assert.deepEqual(uploadedPdfIds(), uploadedBeforeReload, 'concluir vínculos reutiliza exatamente os mesmos arquivos');
  await page.locator('#read-manual').click(); await page.waitForFunction(() => document.querySelector('#reader-status').hidden);
  assert.equal(await page.locator('#reader-document option').count(), 4);
  await page.locator('#reader-close').click();
  await page.reload(); await page.locator('.card-main').click();
  assert.equal(await page.locator('#detail-documents .document-reading-row').count(), 4);
  assert.deepEqual(errors, []); assert.deepEqual(blocked, []); assert.deepEqual(backend.metrics.blockedOutbound, []);
  console.log('Betrayal: principal + 3 PDFs, falha após upload, reload, recuperação criptografada sem reenviar arquivos, vínculo confirmado no Firestore e 4 documentos na ficha/leitor. Correções paralelas preservadas.');
} finally { await browser.close(); await backend.close(); await env.cleanup(); }
